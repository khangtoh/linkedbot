import type { Page } from "playwright";

// What the generator sees of a page: a compact outline in which every interesting element has a
// handle like [n12]. The model refers to elements by handle; code here writes the CSS/Playwright
// selectors and checks that they really find those elements. Handles live in a data-lb-id
// attribute on the page, so they survive between calls until the page is reloaded.

// Under tsx/esbuild (dev and tests) named inner functions are wrapped in a __name() helper that
// does not exist inside the page; define a pass-through before running the scripts below.
async function shim(page: Page): Promise<void> {
  await page.evaluate("globalThis.__name ??= (f) => f");
}

const OUTLINE_SCRIPT = ({ root, maxLines, textLen }: { root: string | null; maxLines: number; textLen: number }) => {
  const w = window as unknown as { __lbSeq?: number };
  const SKIP = new Set(["SCRIPT", "STYLE", "NOSCRIPT", "SVG", "PATH", "TEMPLATE", "LINK", "META", "BR", "HR", "IMG", "PICTURE", "SOURCE", "CODE"]);
  const KEEP = new Set(["H1", "H2", "H3", "H4", "H5", "H6", "A", "BUTTON", "LI", "DT", "DD", "TH", "TD", "P", "TIME", "LABEL", "SPAN", "STRONG", "EM", "SECTION", "ARTICLE", "MAIN", "UL", "OL", "DL", "TABLE", "NAV", "HEADER", "FOOTER", "ASIDE", "FIGURE", "FIGCAPTION"]);
  const clip = (s: string) => (s.length > textLen ? `${s.slice(0, textLen)}…` : s);
  const handle = (el: Element) => {
    const e = el as HTMLElement;
    if (!e.dataset.lbId) e.dataset.lbId = `n${(w.__lbSeq = (w.__lbSeq ?? 0) + 1)}`;
    return e.dataset.lbId;
  };
  const visible = (el: Element) => {
    const r = el.getBoundingClientRect();
    if (r.width === 0 && r.height === 0) return false;
    const cs = getComputedStyle(el);
    return cs.display !== "none" && cs.visibility !== "hidden";
  };
  const ownText = (el: Element) =>
    Array.from(el.childNodes)
      .filter((n) => n.nodeType === 3)
      .map((n) => n.textContent ?? "")
      .join(" ")
      .replace(/\s+/g, " ")
      .trim();
  const lines: string[] = [];
  let dropped = 0;
  const describe = (el: Element) => {
    const parts = [`[${handle(el)}] ${el.tagName.toLowerCase()}`];
    const role = el.getAttribute("role");
    if (role) parts.push(`role=${role}`);
    const label = el.getAttribute("aria-label");
    if (label) parts.push(`label="${clip(label)}"`);
    if (el.id && !/\d{3,}|^ember/.test(el.id)) parts.push(`#${el.id}`);
    if (el.tagName === "A") {
      const href = el.getAttribute("href") ?? "";
      try {
        const u = new URL(href, location.href);
        parts.push(`href=${u.host === location.host ? u.pathname : u.host + u.pathname}`);
      } catch {
        parts.push(`href=${clip(href)}`);
      }
    }
    if (["UL", "OL", "TABLE", "DL"].includes(el.tagName)) parts.push(`(${el.children.length} items)`);
    return parts;
  };
  const walk = (el: Element, depth: number) => {
    if (SKIP.has(el.tagName) || !visible(el)) return;
    const text = ownText(el);
    const interesting = KEEP.has(el.tagName) && (text || el.tagName.match(/^(A|BUTTON|UL|OL|DL|TABLE|SECTION|ARTICLE|MAIN|H\d)$/)) || el.getAttribute("role") || el.getAttribute("aria-label");
    let next = depth;
    if (interesting) {
      if (lines.length >= maxLines) {
        dropped++;
      } else {
        const parts = describe(el);
        const leafText = text || (el.children.length === 0 ? "" : el.querySelector("*") && el.children.length <= 2 ? (el as HTMLElement).innerText?.replace(/\s+/g, " ").trim() ?? "" : "");
        if (leafText) parts.push(`"${clip(leafText)}"`);
        lines.push(`${"  ".repeat(depth)}${parts.join(" ")}`);
      }
      next = depth + 1;
    }
    for (const child of Array.from(el.children)) walk(child, next);
  };
  const start = root ? document.querySelector(`[data-lb-id="${root}"]`) : document.body;
  if (!start) return `No element ${root} on this page (handles reset when the page reloads).`;
  walk(start, 0);
  if (dropped) lines.push(`… ${dropped} more element(s) not shown; outline a part of the page by passing its handle`);
  return `${location.pathname}  "${document.title}"\n${lines.join("\n")}`;
};

export async function outline(page: Page, opts: { root?: string; maxLines?: number; textLen?: number } = {}): Promise<string> {
  await shim(page);
  return page.evaluate(OUTLINE_SCRIPT, { root: opts.root ?? null, maxLines: Math.min(opts.maxLines ?? 250, 600), textLen: opts.textLen ?? 80 });
}

// Candidate selectors for one element (mode "single") or for the repeating items of a list that the
// element is one of (mode "list"), most robust first. Generated by code, then each is checked.
const CANDIDATES_SCRIPT = ({ id, mode }: { id: string; mode: "single" | "list" }) => {
  const el = document.querySelector(`[data-lb-id="${id}"]`);
  if (!el) return null;
  const q = (s: string) => JSON.stringify(s);
  const tag = el.tagName.toLowerCase();
  const stableId = (e: Element) => (e.id && !/\d{3,}|^ember|^[a-z0-9]{8,}$/i.test(e.id) ? `#${CSS.escape(e.id)}` : null);
  const attrSel = (e: Element) => {
    for (const a of ["data-test-id", "data-testid", "data-field", "data-section", "aria-label", "name", "itemprop", "role"]) {
      const v = e.getAttribute(a);
      if (v && v.length < 60) return `${e.tagName.toLowerCase()}[${a}=${q(v)}]`;
    }
    return null;
  };
  const shortText = (e: Element) => ((e as HTMLElement).innerText ?? "").replace(/\s+/g, " ").trim();
  // The nearest ancestor that can be named robustly: an id, a test attribute, or a heading inside it.
  const anchorOf = (e: Element): string | null => {
    for (let a = e.parentElement; a && a !== document.body; a = a.parentElement) {
      const named = stableId(a) ?? attrSel(a);
      if (named) return named;
      if (["SECTION", "ARTICLE", "DIV", "LI"].includes(a.tagName)) {
        const h = a.querySelector(":scope > h2, :scope > h3, :scope > div > h2, :scope > header h2");
        const t = h && shortText(h);
        if (t && t.length < 40) return `${a.tagName.toLowerCase()}:has(> ${h!.parentElement === a ? "" : "* > "}${h!.tagName.toLowerCase()}:text-is(${q(t)}))`;
      }
    }
    return null;
  };
  const out: string[] = [];
  if (mode === "single") {
    const own = stableId(el) ?? attrSel(el);
    if (own) out.push(own);
    if (/^h[1-6]$/.test(tag)) out.push(tag, `${tag}:text-is(${q(shortText(el))})`);
    if (tag === "a") {
      const href = el.getAttribute("href") ?? "";
      const m = /^\/(in|company|school|jobs|posts)\//.exec(new URL(href, location.href).pathname);
      if (m) out.push(`a[href*="/${m[1]}/"]`);
    }
    const anchor = anchorOf(el);
    if (anchor) {
      out.push(`${anchor} ${tag}`);
      const sibLabel = el.previousElementSibling && shortText(el.previousElementSibling);
      if (sibLabel && sibLabel.length < 40) out.push(`${anchor} ${el.previousElementSibling!.tagName.toLowerCase()}:text-is(${q(sibLabel)}) + ${tag}`);
    }
    const sibLabel = el.previousElementSibling && shortText(el.previousElementSibling);
    if (sibLabel && sibLabel.length < 40) out.push(`${el.previousElementSibling!.tagName.toLowerCase()}:text-is(${q(sibLabel)}) + ${tag}`);
  } else {
    // Walk up to the element that repeats among its siblings: that is the list item.
    let item: Element = el;
    while (item.parentElement && item.parentElement !== document.body) {
      const same = Array.from(item.parentElement.children).filter((c) => c.tagName === item.tagName);
      if (same.length >= 2) break;
      item = item.parentElement;
    }
    const itag = item.tagName.toLowerCase();
    const parent = item.parentElement!;
    const pname = stableId(parent) ?? attrSel(parent) ?? anchorOf(item);
    if (pname) out.push(`${pname} > ${itag}`, `${pname} ${itag}`);
    const link = item.querySelector("a[href]");
    if (link) {
      const m = /^\/(in|company|school|jobs|posts)\//.exec(new URL(link.getAttribute("href")!, location.href).pathname);
      if (m) out.push(`main ${itag}:has(a[href*="/${m[1]}/"])`, `${itag}:has(a[href*="/${m[1]}/"])`);
    }
    out.push(`${parent.tagName.toLowerCase()} > ${itag}`);
    return { item: (item as HTMLElement).dataset.lbId ?? null, candidates: [...new Set(out)] };
  }
  return { item: id, candidates: [...new Set(out)] };
};

export type SelectorCandidate = { selector: string; count: number; matchesElement: boolean };

export async function selectorsFor(page: Page, handle: string, mode: "single" | "list"): Promise<{ item: string | null; candidates: SelectorCandidate[] } | null> {
  await shim(page);
  const raw = await page.evaluate(CANDIDATES_SCRIPT, { id: handle, mode });
  if (!raw) return null;
  // Make sure the item has a handle, then check every candidate against the live page.
  const target = raw.item ?? (await page.locator(`[data-lb-id="${handle}"]`).evaluate((e, m) => {
    let item: Element = e;
    while (item.parentElement && item.parentElement !== document.body && Array.from(item.parentElement.children).filter((c) => c.tagName === item.tagName).length < 2) item = item.parentElement;
    const h = item as HTMLElement;
    if (!h.dataset.lbId) h.dataset.lbId = `${m}-item`;
    return h.dataset.lbId;
  }, handle));
  const candidates: SelectorCandidate[] = [];
  for (const selector of raw.candidates) {
    const loc = page.locator(selector);
    const count = await loc.count().catch(() => -1);
    if (count <= 0) continue;
    const matchesElement = await loc
      .evaluateAll((els, t) => els.some((e) => (e as HTMLElement).dataset.lbId === t), target)
      .catch(() => false);
    if (!matchesElement) continue;
    if (mode === "single" && count !== 1) continue; // a field selector must name exactly this element
    if (mode === "list" && count < 2) continue;
    candidates.push({ selector, count, matchesElement });
  }
  return { item: target, candidates };
}

// What is at a point of the screen (for "correct by pointing"): the element and its ancestors.
export async function describeAt(page: Page, x: number, y: number): Promise<{ handle: string; box: { x: number; y: number; width: number; height: number }; chain: string[] } | null> {
  await shim(page);
  return page.evaluate(({ x, y }) => {
    const w = window as unknown as { __lbSeq?: number };
    const el = document.elementFromPoint(x, y);
    if (!el) return null;
    const handle = (e: Element) => {
      const h = e as HTMLElement;
      if (!h.dataset.lbId) h.dataset.lbId = `n${(w.__lbSeq = (w.__lbSeq ?? 0) + 1)}`;
      return h.dataset.lbId;
    };
    const chain: string[] = [];
    for (let a: Element | null = el; a && a !== document.body && chain.length < 6; a = a.parentElement) {
      chain.push(`[${handle(a)}] ${a.tagName.toLowerCase()} "${((a as HTMLElement).innerText ?? "").replace(/\s+/g, " ").trim().slice(0, 60)}"`);
    }
    const r = el.getBoundingClientRect();
    return { handle: handle(el), box: { x: r.x, y: r.y, width: r.width, height: r.height }, chain };
  }, { x, y });
}
